"""Phase 3G genuine Ed25519 + immutable metadata + anti-rollback E2E tests.

All signing keys are generated by OpenSSL inside a temporary test directory;
production material and real release signatures are never created or stored.
"""
import base64
from datetime import datetime, timezone, timedelta
import hashlib
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch

sys.path.insert(0,str(Path(__file__).resolve().parents[1]/'tools'))
import appforge_phase3g_integrated_v9 as g

NOW=datetime.now(timezone.utc).replace(microsecond=0)


def openssl(*args):
    return subprocess.run(['openssl',*map(str,args)],check=True,
        capture_output=True,timeout=20).stdout


class Phase3GEndToEnd(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp=tempfile.TemporaryDirectory(prefix='appforge-v9-3g-keys-')
        cls.folder=Path(cls.tmp.name)
        cls.keys={}
        for name in ('old','new','rel_a','rel_b','untrusted'):
            priv=cls.folder/(name+'.key')
            openssl('genpkey','-algorithm','ED25519','-out',priv)
            der=openssl('pkey','-in',priv,'-pubout','-outform','DER')
            identity=g.crypto.spki(der)
            cls.keys[name]={'private':priv,'der':der,'id':identity,
                'entry':{'keyid':identity,'spki_der_b64':base64.b64encode(der).decode('ascii')}}

    @classmethod
    def tearDownClass(cls):
        cls.tmp.cleanup()

    def setUp(self):
        t=tempfile.TemporaryDirectory(prefix='appforge-v9-3g-case-')
        self.addCleanup(t.cleanup)
        self.d=Path(t.name)
        evidence={'schema':1,'stage':'OFFLINE_EVIDENCE_ONLY',
            'snapshot':g.crypto.SNAPSHOT,'original_objects_verified':218,
            'original_deb_objects_verified':214,'ubuntu_inrelease_verified':4,
            'signed_packages_indexes_verified':32,
            'distinct_content_addressed_objects':248,
            'distinct_content_addressed_bytes':650832480,
            'appforge_ed25519_release_signature':'NOT_PRESENT',
            'r2_upload_allowed':False,'public_distribution_allowed':False,
            'android_client_enabled':False,'apt_ready':False,'all_engines_ready':False}
        self.evidence=self.d/'fixture-evidence.json'
        self.evidence.write_bytes(g.crypto.canonical(evidence))
        self.digest=hashlib.sha256(self.evidence.read_bytes()).hexdigest()
        self.pub=self.d/'trusted-root.der'
        self.pub.write_bytes(self.keys['old']['der'])
        self.root_path=self.d/'root.json'
        self.release_path=self.d/'release.json'
        self.root=self.make_root()
        self.release=self.make_release()
        self.write()

    def stamp(self,delta):
        return (NOW+timedelta(days=delta)).strftime('%Y-%m-%dT%H:%M:%SZ')

    def sign(self, name, context, payload):
        source=self.d/'signed-message'
        source.write_bytes(context+g.crypto.canonical(payload))
        sig=openssl('pkeyutl','-sign','-inkey',self.keys[name]['private'],
                    '-rawin','-in',source)
        self.assertEqual(len(sig),64)
        return {'keyid':self.keys[name]['id'],
                'sig_b64':base64.b64encode(sig).decode('ascii')}

    def make_root(self,version=1,rotate=False,threshold=1,signers=None):
        rootkey='new' if rotate else 'old'
        payload={'schema':1,'role':'appforge-v9-root','version':version,
            'issued_at':self.stamp(-1),'expires_at':self.stamp(30),
            'root_key':self.keys[rootkey]['entry'],
            'release_keys':[self.keys[n]['entry'] for n in ('rel_a','rel_b')],
            'release_threshold':threshold}
        if signers is None:
            signers=('old','new') if rotate else ('old',)
        return {'payload':payload,'signatures':[
            self.sign(name,g.crypto.ROOT_CONTEXT,payload) for name in signers]}

    def make_release(self,seq=1,root_version=1,signers=('rel_a',)):
        payload={'schema':1,'role':'appforge-v9-release','root_version':root_version,
            'sequence':seq,'snapshot':g.crypto.SNAPSHOT,'evidence_sha256':self.digest,
            'issued_at':self.stamp(-1),'expires_at':self.stamp(21),
            'r2_upload_allowed':False,'public_distribution_allowed':False,
            'android_client_enabled':False}
        return {'payload':payload,'signatures':[
            self.sign(name,g.crypto.RELEASE_CONTEXT,payload) for name in signers]}

    def resign(self,kind,signers):
        obj=self.root if kind=='root' else self.release
        context=g.crypto.ROOT_CONTEXT if kind=='root' else g.crypto.RELEASE_CONTEXT
        obj['signatures']=[self.sign(name,context,obj['payload']) for name in signers]

    def write(self):
        self.root_path.write_bytes(g.crypto.canonical(self.root))
        self.release_path.write_bytes(g.crypto.canonical(self.release))

    def evaluate(self,old=None,checkpoint=None):
        kwargs={'evidence':self.evidence,'root_metadata':self.root_path,
                'release_metadata':self.release_path,'now':NOW}
        if old is None:
            kwargs.update(first_root_public_der=self.pub,
                          first_root_pin=self.keys['old']['id'])
        else:
            kwargs.update(old_state=old,external_checkpoint=checkpoint)
        # Test-only substitution of evidence digest on BOTH independent pins:
        # this never accepts a user-supplied pin in production evaluate()/CLI.
        with patch.object(g.crypto,'EVIDENCE_PIN',self.digest),\
             patch.object(g.policy,'EVIDENCE',self.digest):
            return g.evaluate(**kwargs)

    def checkpoint(self, candidate):
        location=self.d/'checkpointed-state.json'
        raw=g.policy.canonical(candidate)
        location.write_bytes(raw)
        return location,hashlib.sha256(raw).hexdigest()

    def initial(self):
        return self.checkpoint(self.evaluate())

    def next_release(self,seq=2):
        self.release=self.make_release(seq=seq)
        self.write()

    def test_01_real_bootstrap_signatures(self):
        self.assertEqual(self.evaluate()['release_sequence'],1)

    def test_02_successful_signed_update(self):
        old,cp=self.initial();self.next_release()
        result=self.evaluate(old,cp)
        self.assertEqual((result['release_sequence'],result['root_version']),(2,1))

    def test_03_exact_replay_idempotent(self):
        old,cp=self.initial()
        self.assertEqual(self.evaluate(old,cp),self.evaluate())

    def test_04_release_rollback_rejected(self):
        old,cp=self.initial();self.next_release()
        s=self.evaluate(old,cp);old2,cp2=self.checkpoint(s)
        self.release=self.make_release(seq=1);self.write()
        with self.assertRaisesRegex(ValueError,'rollback'):
            self.evaluate(old2,cp2)

    def test_05_same_sequence_different_signed_envelope_rejected(self):
        old,cp=self.initial()
        self.release['payload']['expires_at']=self.stamp(22)
        self.resign('release',('rel_a',));self.write()
        with self.assertRaisesRegex(ValueError,'same sequence'):
            self.evaluate(old,cp)

    def test_06_unsigned_release_payload_mutation_rejected(self):
        old,cp=self.initial();self.release['payload']['sequence']=2;self.write()
        with self.assertRaisesRegex(ValueError,'signature verification failed'):
            self.evaluate(old,cp)

    def test_07_unsigned_root_payload_mutation_rejected(self):
        self.root['payload']['release_threshold']=2;self.write()
        with self.assertRaisesRegex(ValueError,'signature verification failed'):
            self.evaluate()

    def test_08_signed_expired_release_rejected(self):
        self.release['payload']['expires_at']=self.stamp(-0.5)
        self.resign('release',('rel_a',));self.write()
        with self.assertRaisesRegex(ValueError,'expired'):
            self.evaluate()

    def test_09_signed_future_root_rejected(self):
        self.root['payload']['issued_at']=self.stamp(2)
        self.resign('root',('old',));self.write()
        with self.assertRaisesRegex(ValueError,'future-dated'):
            self.evaluate()

    def test_10_genuine_dual_signature_root_rotation(self):
        old,cp=self.initial()
        self.root=self.make_root(version=2,rotate=True)
        self.release=self.make_release(seq=2,root_version=2);self.write()
        state=self.evaluate(old,cp)
        self.assertEqual(state['root_keyid'],self.keys['new']['id'])
        self.assertEqual(state['root_version'],2)
        nextstate,cp2=self.checkpoint(state)
        self.release=self.make_release(seq=3,root_version=2);self.write()
        self.assertEqual(self.evaluate(nextstate,cp2)['release_sequence'],3)

    def test_11_rotation_without_old_signature_rejected(self):
        old,cp=self.initial()
        self.root=self.make_root(version=2,rotate=True,signers=('new',))
        self.release=self.make_release(seq=2,root_version=2);self.write()
        with self.assertRaisesRegex(ValueError,'previous trusted root'):
            self.evaluate(old,cp)

    def test_12_rotation_without_new_signature_rejected(self):
        old,cp=self.initial()
        self.root=self.make_root(version=2,rotate=True,signers=('old',))
        self.release=self.make_release(seq=2,root_version=2);self.write()
        with self.assertRaisesRegex(ValueError,'new root possession'):
            self.evaluate(old,cp)

    def test_13_root_version_skip_rejected(self):
        old,cp=self.initial()
        self.root=self.make_root(version=3,rotate=True)
        self.release=self.make_release(seq=2,root_version=3);self.write()
        with self.assertRaisesRegex(ValueError,'rotation skip'):
            self.evaluate(old,cp)

    def test_14_same_root_version_equivocation_rejected(self):
        old,cp=self.initial();self.root=self.make_root(threshold=2)
        self.release=self.make_release(seq=2,signers=('rel_a','rel_b'))
        self.write()
        with self.assertRaisesRegex(ValueError,'equivocation'):
            self.evaluate(old,cp)

    def test_15_broken_json_state_rejected(self):
        old,cp=self.initial();old.write_bytes(b'{bad-json')
        self.next_release()
        with self.assertRaises(ValueError):
            self.evaluate(old,cp)

    def test_16_missing_state_rejected(self):
        old,cp=self.initial();old.unlink();self.next_release()
        with self.assertRaisesRegex(ValueError,'missing'):
            self.evaluate(old,cp)

    def test_17_unauthenticated_checkpoint_rejected(self):
        old,cp=self.initial();self.next_release()
        with self.assertRaisesRegex(ValueError,'checkpoint mismatch'):
            self.evaluate(old,'f'*64)

    def test_18_valid_hash_of_invalid_state_not_sufficient(self):
        old,cp=self.initial()
        corrupted=self.evaluate();corrupted['release_sequence']=False
        old,cp=self.checkpoint(corrupted);self.next_release()
        with self.assertRaisesRegex(ValueError,'release_sequence'):
            self.evaluate(old,cp)

    def test_19_evidence_tampered_rejected(self):
        self.evidence.write_bytes(self.evidence.read_bytes()+b' ')
        with self.assertRaisesRegex(ValueError,'canonical'):
            self.evaluate()

    def test_20_safely_signed_distribution_enable_rejected(self):
        self.release['payload']['r2_upload_allowed']=True
        self.resign('release',('rel_a',));self.write()
        with self.assertRaisesRegex(ValueError,'distribution must remain disabled'):
            self.evaluate()

    def test_21_two_signer_threshold_enforced(self):
        self.root=self.make_root(threshold=2);self.write()
        with self.assertRaisesRegex(ValueError,'threshold'):
            self.evaluate()
        self.release=self.make_release(signers=('rel_a','rel_b'));self.write()
        self.assertEqual(self.evaluate()['release_sequence'],1)

    def test_22_untrusted_release_signer_rejected(self):
        self.release=self.make_release(signers=('untrusted',));self.write()
        with self.assertRaisesRegex(ValueError,'untrusted release signer'):
            self.evaluate()

    def test_23_failed_update_never_modifies_state_bytes(self):
        old,cp=self.initial();before=old.read_bytes()
        self.next_release();self.release['payload']['sequence']=3;self.write()
        with self.assertRaisesRegex(ValueError,'signature verification failed'):
            self.evaluate(old,cp)
        self.assertEqual(old.read_bytes(),before)
        self.assertEqual(hashlib.sha256(old.read_bytes()).hexdigest(),cp)

    def test_24_single_metadata_snapshot_per_file(self):
        orig=g.crypto.read_canonical;paths=[]
        def counted(p,*args,**kwargs):
            paths.append(str(p))
            return orig(p,*args,**kwargs)
        with patch.object(g.crypto,'read_canonical',side_effect=counted),\
             patch.object(g.crypto,'verify_all',side_effect=AssertionError('unsafe re-read')):
            self.assertEqual(self.evaluate()['release_sequence'],1)
        self.assertEqual(paths.count(str(self.root_path)),1)
        self.assertEqual(paths.count(str(self.release_path)),1)

    def test_25_missing_authenticated_checkpoint_fails_closed(self):
        old,cp=self.initial();self.next_release()
        with self.assertRaisesRegex(ValueError,'external trusted checkpoint'):
            self.evaluate(old,None)

    def test_26_root_and_release_evidence_snapshot_lock(self):
        self.release['payload']['snapshot']='20990101T000000Z'
        self.resign('release',('rel_a',));self.write()
        with self.assertRaisesRegex(ValueError,'evidence binding mismatch'):
            self.evaluate()

    def test_27_no_distribution_or_persistent_state_writes(self):
        src=Path(g.__file__).read_text()
        for forbidden in ('genpkey','-sign\'','os.replace(','.write_bytes(','r2.put(', 'aws s3'):
            self.assertNotIn(forbidden,src)
        self.assertIn('TRUST_STATE_PERSISTED=NO',src)


if __name__=='__main__':
    unittest.main()
